set -e

VERSION="v1.0.0"
REPORT_FILE="/tmp/rk3588_env_report_$(date +%Y%m%d_%H%M%S).html"
PASS_COUNT=0
FAIL_COUNT=0
WARN_COUNT=0

# 颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

print_banner() {
    echo "============================================"
    echo "  RK3588 环境检测工具 v${VERSION}"
    echo "  RK3588 Environment Check Tool"
    echo "============================================"
    echo ""
}

check_result() {
    local status=$1
    local item=$2
    local detail=$3
    local suggestion=$4

    if [ "$status" = "PASS" ]; then
        echo -e "  [${GREEN}PASS${NC}] $item"
        PASS_COUNT=$((PASS_COUNT + 1))
    elif [ "$status" = "WARN" ]; then
        echo -e "  [${YELLOW}WARN${NC}] $item"
        WARN_COUNT=$((WARN_COUNT + 1))
    else
        echo -e "  [${RED}FAIL${NC}] $item"
        FAIL_COUNT=$((FAIL_COUNT + 1))
    fi
    echo "         → $detail"
    [ -n "$suggestion" ] && echo "         → 建议：$suggestion"
}


